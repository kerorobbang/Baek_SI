// Bold the "Baek" author name
function authorsHtml(authors) {
  return esc(authors).replace(/S\. Baek/g, "<strong>S. Baek</strong>");
}

/* ---- Modal ---- */
const modal = document.getElementById("pubModal");
function openModal(p) {
  document.getElementById("modalTitle").textContent = p.title;
  document.getElementById("modalAuthors").innerHTML = authorsHtml(p.authors);
  document.getElementById("modalVenue").textContent = p.venue;

  const badges = document.getElementById("modalBadges");
  badges.innerHTML =
    `<span class="px-3 py-1 text-xs font-label-bold uppercase rounded-full tracking-wide ${TOPIC_COLORS[p.topic] || "bg-surface-container-high text-on-surface"}">${esc(p.topic)}</span>` +
    `<span class="px-3 py-1 text-xs font-label-bold uppercase rounded-full tracking-wide bg-surface-container-high dark:bg-primary text-on-surface dark:text-surface-variant">${p.year}</span>`;

  document.getElementById("modalDetails").innerHTML =
    `<div class="flex gap-2"><dt class="font-semibold text-primary dark:text-inverse-primary min-w-[90px]">Authors</dt><dd>${authorsHtml(p.authors)}</dd></div>` +
    `<div class="flex gap-2"><dt class="font-semibold text-primary dark:text-inverse-primary min-w-[90px]">Published in</dt><dd>${esc(p.venue)}</dd></div>` +
    `<div class="flex gap-2"><dt class="font-semibold text-primary dark:text-inverse-primary min-w-[90px]">Year</dt><dd>${p.year}</dd></div>` +
    (p.doi ? `<div class="flex gap-2"><dt class="font-semibold text-primary dark:text-inverse-primary min-w-[90px]">DOI</dt><dd><a class="text-secondary dark:text-secondary-fixed underline break-all" href="${doiUrl(p.doi)}" target="_blank" rel="noopener">${esc(p.doi)}</a></dd></div>` : "");

  document.getElementById("modalScholar").href = scholarSearch(p.title);

  const copyBtn = document.getElementById("copyCite");
  copyBtn.onclick = () => {
    const citation = `${p.authors} (${p.year}). ${p.title}. ${p.venue}.${p.doi ? " https://doi.org/" + p.doi : ""}`;
    navigator.clipboard && navigator.clipboard.writeText(citation).then(() => {
      copyBtn.innerHTML = '<span class="material-symbols-outlined">check</span> Copied';
      setTimeout(() => { copyBtn.innerHTML = '<span class="material-symbols-outlined">content_copy</span> Copy Citation'; }, 1800);
    });
  };

  modal.classList.add("active");
  document.body.style.overflow = "hidden";
}
function closeModal() {
  modal.classList.remove("active");
  document.body.style.overflow = "";
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-publication-count]").forEach(el => {
    el.textContent = String(PUBLICATIONS.length);
  });
  document.querySelectorAll("[data-publications-year]").forEach(el => {
    const yr = Number(el.dataset.publicationsYear);
    el.textContent = String(PUBLICATIONS.filter(p => p.year === yr).length);
  });
  // On Home and CV the shared script updates counts only.
  if (!document.getElementById("pubList")) return;
  // Quick tags from topics
  const tags = document.getElementById("quickTags");
  Object.keys(TOPIC_COLORS).forEach((t) => {
    const span = document.createElement("span");
    span.className = "inline-flex items-center px-3 py-1 rounded-full text-sm font-medium bg-surface-container-high dark:bg-primary text-on-surface dark:text-surface-variant cursor-pointer hover:bg-secondary hover:text-on-secondary transition-colors";
    span.textContent = t;
    span.addEventListener("click", () => {
      const sel = document.getElementById("topicFilter");
      sel.value = (state.topic === t) ? "" : t;
      state.topic = sel.value;
      updateTagStyles();
      render();
    });
    tags.appendChild(span);
  });

  function updateTagStyles() {
    [...tags.children].forEach((span) => {
      const active = span.textContent === state.topic;
      span.classList.toggle("bg-secondary", active);
      span.classList.toggle("text-on-secondary", active);
      span.classList.toggle("bg-surface-container-high", !active);
    });
  }

  document.getElementById("search").addEventListener("input", (e) => { state.q = e.target.value; render(); });
  document.getElementById("topicFilter").addEventListener("change", (e) => { state.topic = e.target.value; updateTagStyles(); render(); });
  document.getElementById("yearFilter").addEventListener("change", (e) => { state.year = e.target.value; render(); });

  document.getElementById("closeModal").addEventListener("click", closeModal);
  modal.addEventListener("click", (e) => { if (e.target === modal) closeModal(); });
  document.addEventListener("keydown", (e) => { if (e.key === "Escape") closeModal(); });

  render();
});
