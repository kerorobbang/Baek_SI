const scholarSearch = (title) => "https://scholar.google.com/scholar?q=" + encodeURIComponent(title);
const doiUrl = (doi) => "https://doi.org/" + encodeURIComponent(doi).replace(/%2F/g, "/");
const esc = (s) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));

const state = { q: "", topic: "", year: "" };

function matches(p) {
  if (state.topic && p.topic !== state.topic) return false;
  if (state.year && String(p.year) !== state.year) return false;
  if (state.q) {
    const hay = (p.title + " " + p.authors + " " + p.venue + " " + p.topic).toLowerCase();
    if (!hay.includes(state.q.toLowerCase())) return false;
  }
  return true;
}

function render() {
  const list = document.getElementById("pubList");
  const filtered = PUBLICATIONS.filter(matches);
  const byYear = {};
  filtered.forEach((p, i) => {
    p._idx = PUBLICATIONS.indexOf(p);
    (byYear[p.year] = byYear[p.year] || []).push(p);
  });
  const years = Object.keys(byYear).sort((a, b) => b - a);

  document.getElementById("resultCount").textContent =
    filtered.length + (filtered.length === 1 ? " publication" : " publications");
  document.getElementById("noResults").classList.toggle("hidden", filtered.length > 0);

  list.innerHTML = years.map((yr) => `
    <div>
      <div class="flex items-center gap-4 mb-stack-md">
        <h2 class="font-headline-lg text-headline-lg text-primary dark:text-inverse-primary">${yr}</h2>
        <div class="h-px bg-outline-variant flex-grow"></div>
        <span class="font-label-bold text-label-bold text-on-surface-variant dark:text-surface-variant">${byYear[yr].length}</span>
      </div>
      <div class="grid grid-cols-1 gap-6">
        ${byYear[yr].map((p) => card(p)).join("")}
      </div>
    </div>`).join("");

  list.querySelectorAll(".pub-card").forEach((el) => {
    el.addEventListener("click", () => openModal(PUBLICATIONS[el.dataset.idx]));
  });
}

